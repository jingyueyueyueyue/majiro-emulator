"""Build the shared VM's Android SDL3 host from pinned source dependencies."""
from __future__ import annotations
from concurrent.futures import ThreadPoolExecutor
import os
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "convert"))
from generate_portable_pixels import generate
from port_common import ROOT, archive_dir, atomic_bytes, read_json, sha256, timestamp, write_json


def native_inputs():
    paths=set()
    for base in ("player/core","references/player/lua/src","references/player/SDL3/include"):
        paths.update(path for path in (ROOT/base).rglob("*")
                     if path.is_file()and path.suffix in(".cpp",".hpp",".inc",".c",".h"))
    paths.update(ROOT/name for name in(
        "player/android/game_host.cpp","player/android/render_recovery.hpp","player/native/majiro_pixels.cpp",
        "scripts/convert/generate_portable_pixels.py","scripts/build/build_android_game.py",
        "references/majiro-py/opcodes.py","references/player/SDL3/arm64-v8a/libSDL3.so"))
    return {path.relative_to(ROOT).as_posix():sha256(path)for path in sorted(paths)}


def main():
    inputs=native_inputs()
    tools = read_json(ROOT / "reports/android_toolchain.json")
    if tools["status"] != "ready":
        raise RuntimeError("Android native toolchain is not ready")
    sdk = Path(tools["sdk"])
    compiler_root = sdk / "ndk/28.2.13676358/toolchains/llvm/prebuilt/windows-x86_64/bin"
    clang, clangxx, archiver = compiler_root / "clang.exe", compiler_root / "clang++.exe", compiler_root / "llvm-ar.exe"
    evidence = archive_dir("android_game_build")
    generated = evidence / "portable_pixels.cpp"
    generate(generated)
    # Reuse the exact encoding table generated by the parser build.
    from majiro_mjo import opcode_table
    definitions = opcode_table()
    table = "#pragma once\n#include <array>\n#include <cstdint>\nnamespace majiro {\n" \
            "struct Opcode{uint16_t code;const char* encoding;};\n" \
            f"inline constexpr std::array<Opcode,{len(definitions)}> kOpcodes={{{{\n" \
            + ",\n".join(f'{{{code},"{encoding}"}}'for code,(_,encoding)in sorted(definitions.items())) \
            + "\n}};\n}\n"
    (evidence / "majiro_opcodes.hpp").write_text(table, encoding="ascii")
    lua_root = ROOT / "references/player/lua/src"
    sdl = ROOT / "references/player/SDL3"
    if not (lua_root / "lua.h").is_file() or not (sdl / "arm64-v8a/libSDL3.so").is_file():
        raise RuntimeError("fetch_player_dependencies.py must pass first")
    common = ["--target=aarch64-linux-android26", "-O2", "-fPIC", "-fvisibility=hidden"]
    c_sources = [p for p in lua_root.glob("*.c") if p.name not in ("lua.c", "luac.c", "print.c")]

    def compile_c(source):
        output = evidence / (source.stem + ".o")
        result = subprocess.run([str(clang), *common, "-DLUA_USE_LINUX",
                                 "-c", str(source), "-o", str(output)], capture_output=True)
        (evidence / (source.stem + ".txt")).write_bytes(result.stdout + result.stderr)
        if result.returncode:
            raise RuntimeError("Lua C compilation failed: " + str(source))
        return output
    with ThreadPoolExecutor(max_workers=6) as pool:
        objects = list(pool.map(compile_c, c_sources))
    library = evidence / "liblua.a"
    subprocess.run([str(archiver), "rcs", str(library), *map(str, objects)], check=True, capture_output=True)
    sources = [
        ROOT / "player/core/majiro_core.cpp", ROOT / "player/core/majiro_image.cpp",
        ROOT / "player/core/majiro_save.cpp",
        ROOT / "player/core/majiro_story_save.cpp",
        ROOT / "player/core/lua_script.cpp", ROOT / "player/android/game_host.cpp", generated]
    binary = evidence / "libmajiro_game.so"
    command = [
        str(clangxx), *common, "-std=c++20", "-shared", "-static-libstdc++", "-DMAJIRO_DEBUG_BRIDGE",
        "-I" + str(evidence), "-I" + str(ROOT / "player/core"), "-I" + str(lua_root),
        "-I" + str(sdl / "include"), *map(str, sources), str(library),
        "-L" + str(sdl / "arm64-v8a"), "-lSDL3", "-llog", "-landroid", "-ldl", "-lm",
        "-Wl,-z,max-page-size=16384", "-Wl,--no-undefined", "-o", str(binary),
    ]
    result = subprocess.run(command, capture_output=True, cwd=evidence)
    (evidence / "link.txt").write_bytes(result.stdout + result.stderr)
    if result.returncode:
        print((result.stdout + result.stderr).decode("utf-8", "replace")[-10000:])
        raise RuntimeError("Android game host compilation failed: " + str(evidence / "link.txt"))
    destination = ROOT / "resources/player/android/arm64-v8a/libmajiro_game.so"
    atomic_bytes(destination, binary.read_bytes())
    record = {
        "status": "cross_compiled", "timestamp": timestamp(), "library": str(destination),
        "sha256": sha256(destination), "sdl_sha256": sha256(sdl / "arm64-v8a/libSDL3.so"),
        "runtime_sha256": {p.name: sha256(p) for p in (ROOT / "player/runtime").glob("*.lua")},
        "source_sha256": {str(p.relative_to(ROOT)): sha256(p) for p in sources if p != generated},
        "pixel_source_sha256": sha256(ROOT / "player/native/majiro_pixels.cpp"),
        "screen_view_sha256":sha256(ROOT/"player/core/screen_view.hpp"),
        "input_sha256":inputs,
        "device_verified": False, "full_gameplay_verified": False,
        "build_evidence": str(evidence),
    }
    if inputs!=native_inputs():
        raise RuntimeError("Android native inputs changed during compilation; rebuild before packaging")
    write_json(ROOT / "reports/android_game_build.json", record)
    for path in [*objects, library, binary]:
        path.unlink(missing_ok=True)
    print("Android SDL3 + Lua VM host built:", destination)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
